let current = 'zh-CN';

export function getLocale() {
  return current;
}

export function setLocale(id) {
  current = I18N[id] ? id : 'zh-CN';
  try { localStorage.setItem('bc.locale', current); } catch { /* noop */ }
  document.documentElement.setAttribute('lang', current === 'en' ? 'en' : 'zh-CN');
  return current;
}

export function initLocale(fallback = 'zh-CN') {
  let saved = null;
  try { saved = localStorage.getItem('bc.locale'); } catch { /* noop */ }
  return setLocale(saved || fallback || 'zh-CN');
}

/** 翻译，支持 {name} 占位符 */
export function t(key, params = {}) {
  const dict = I18N[current] || I18N['zh-CN'];
  let str = dict[key] ?? I18N['zh-CN'][key] ?? key;
  for (const [k, v] of Object.entries(params)) {
    str = str.replaceAll(`{${k}}`, String(v));
  }
  return str;
}

/** 把所有 [data-i18n] 元素翻译一遍 */
export function applyI18n(root = document) {
  root.querySelectorAll('[data-i18n]').forEach((el) => {
    const key = el.getAttribute('data-i18n');
    if (key) el.textContent = t(key);
  });
  root.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (key) el.setAttribute('placeholder', t(key));
  });
  root.querySelectorAll('[data-i18n-title]').forEach((el) => {
    const key = el.getAttribute('data-i18n-title');
    if (key) el.setAttribute('title', t(key));
  });
}
